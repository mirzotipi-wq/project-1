//! Cassa POS OS — build system.
//!
//! Everything the OS is made of is authored in Zig, including the linker
//! script, which is generated as a build artifact instead of being committed
//! as a second language. The only external tools are the Zig compiler itself
//! and (optionally) QEMU for running the kernel during development.

const std = @import("std");

const klog = std.log.scoped(.build);

/// The kernel is a single-image, higher-EL bare-metal program.
const kernel_query: std.Target.Query = .{
    .cpu_arch = .aarch64,
    .os_tag = .freestanding,
    .abi = .none,
    // ARMv8.0-A baseline: boots on every 64-bit ARM core in production today
    // (Cortex-A53/A55/A72/A76/A78/X1, Neoverse N1/N2/V1, Apple, Graviton...).
    .cpu_model = .{ .explicit = &std.Target.aarch64.cpu.cortex_a53 },
    .cpu_features_add = std.Target.aarch64.featureSet(&.{ .neon, .fp_armv8 }),
};

/// Physical load address used by the QEMU `virt` machine when `-kernel` is
/// given an ELF image. Real hardware enters through the UEFI stub instead,
/// which relocates the image to whatever it likes; both paths share `_start`.
const kernel_load_address = 0x4008_0000;

fn linkerScript(b: *std.Build) []const u8 {
    return b.fmt(
        \\/* Generated by build.zig — do not edit. */
        \\ENTRY(_start)
        \\
        \\SECTIONS
        \\{{
        \\  . = 0x{x};
        \\  __kernel_start = .;
        \\
        \\  .text : ALIGN(4096) {{
        \\    KEEP(*(.text.boot))
        \\    *(.text .text.*)
        \\  }}
        \\
        \\  .rodata : ALIGN(4096) {{
        \\    *(.rodata .rodata.*)
        \\  }}
        \\
        \\  .data : ALIGN(4096) {{
        \\    *(.data .data.*)
        \\  }}
        \\
        \\  .bss (NOLOAD) : ALIGN(4096) {{
        \\    __bss_start = .;
        \\    *(.bss .bss.*)
        \\    *(COMMON)
        \\    . = ALIGN(16);
        \\    __bss_end = .;
        \\  }}
        \\
        \\  . = ALIGN(65536);
        \\  __kernel_end = .;
        \\
        \\  /DISCARD/ : {{
        \\    *(.comment)
        \\    *(.eh_frame .eh_frame_hdr)
        \\    *(.note .note.*)
        \\    *(.debug*)
        \\  }}
        \\}}
        \\
    , .{kernel_load_address});
}

pub fn build(b: *std.Build) void {
    const optimize = b.standardOptimizeOption(.{ .preferred_optimize_mode = .ReleaseSmall });

    // ---------------------------------------------------------------- kernel
    const ktarget = b.resolveTargetQuery(kernel_query);

    const kmod = b.createModule(.{
        .root_source_file = b.path("src/main.zig"),
        .target = ktarget,
        .optimize = optimize,
        .single_threaded = true,
        .strip = false,
        .omit_frame_pointer = false,
        .red_zone = false,
        .stack_check = false,
        .stack_protector = false,
        .pic = false,
        .unwind_tables = .none,
        .code_model = .small,
    });

    const kernel = b.addExecutable(.{
        .name = "cassa",
        .root_module = kmod,
    });

    const wf = b.addWriteFiles();
    kernel.setLinkerScript(wf.add("cassa.ld", linkerScript(b)));
    kernel.step.dependOn(&wf.step);

    b.installArtifact(kernel);

    // ------------------------------------------------------------------- run
    const qemu = b.option([]const u8, "qemu", "QEMU executable") orelse "qemu-system-aarch64";
    const run_cmd = b.addSystemCommand(&.{
        qemu,
        "-machine", "virt",
        "-cpu",   "cortex-a53",
        "-m",     "512M",
        "-smp",   "4",
        "-nographic",
        "-serial", "mon:stdio",
        "-no-reboot",
    });
    run_cmd.addArg("-kernel");
    run_cmd.addArtifactArg(kernel);
    const run_step = b.step("run", "Boot the kernel under QEMU (aarch64 virt)");
    run_step.dependOn(&run_cmd.step);

    // ------------------------------------------------------------------ test
    // Pure logic (allocators, formatting, schedulers, protocol codecs) is
    // unit-tested on the host, where a normal debugger is available.
    const test_mod = b.createModule(.{
        .root_source_file = b.path("src/tests.zig"),
        .target = b.graph.host,
        .optimize = .Debug,
    });
    const unit_tests = b.addTest(.{ .root_module = test_mod });
    const run_unit_tests = b.addRunArtifact(unit_tests);
    const test_step = b.step("test", "Run host unit tests");
    test_step.dependOn(&run_unit_tests.step);

    klog.debug("kernel load address: 0x{x}", .{kernel_load_address});
}
